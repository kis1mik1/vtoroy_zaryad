@dataclass(frozen=True)
class Example:
    title: str
    description: str
    label: str
    case: str = ""


def read_examples(path: Path) -> list[Example]:
    with path.open(encoding="utf-8", newline="") as file:
        return [
            Example(row["title"], row["description"], row["label"], row.get("case") or "")
            for row in csv.DictReader(file)
        ]


def write_examples(path: Path, examples: list[Example]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as file:
        writer = csv.writer(file)
        writer.writerow(["title", "description", "label"])
        for example in examples:
            writer.writerow([example.title, example.description, example.label])


def _category_tree() -> list[dict]:
    return json.loads((CATALOG_DIR / "categories.json").read_text(encoding="utf-8"))


def category_leaves() -> dict[str, list[str]]:
    return {
        root["slug"]: [child["slug"] for child in root.get("children", [])] or [root["slug"]]
        for root in _category_tree()
    }


def label_names() -> dict[str, str]:
    return {root["slug"]: root["name"] for root in _category_tree()} | {OTHER: "Не электроника"}


