class DatasetBuilder:
    def __init__(self, seed: int = 2026):
        self.rng = random.Random(seed)

    def build(self) -> list[Example]:
        examples = self.electronics() + self.other()
        self.rng.shuffle(examples)
        return examples

    def catalog_titles(self) -> dict[str, list[str]]:
        titles: dict[str, list[str]] = {leaf: [] for leaf in LEAVES}
        for path in sorted((CATALOG_DIR / "models").glob("*.json")):
            data = json.loads(path.read_text(encoding="utf-8"))
            for brand, models in data["brands"].items():
                for model in models:
                    titles[data["category"]].extend(self.model_titles(brand, model))
        return titles

    def model_titles(self, brand: str, model: dict) -> list[str]:
        name = model["name"]
        full = name if name.lower().startswith(brand.lower()) else f"{brand} {name}"
        variants = [full, name, *model.get("aliases", []), *generate_aliases(full)[:2]]
        options = [value for values in model.get("options", {}).values() for value in values]
        result = []
        for variant in variants:
            extra = self.rng.choice(options) if options and self.rng.random() < 0.5 else ""
            result.append(f"{variant}, {extra}" if extra else variant)
        return result

    def electronics(self) -> list[Example]:
        catalog = self.catalog_titles()
        examples = []
        for root, leaves in category_leaves().items():
            for _ in range(PER_CATEGORY):
                leaf = self.rng.choice(leaves)
                items, details = LEAVES[leaf]
                use_catalog = catalog[leaf] and self.rng.random() < CATALOG_SHARE
                base = self.rng.choice(catalog[leaf] if use_catalog else items)
                if self.rng.random() < NOUN_TITLE_RATE:
                    base = self.noun_title(leaf, base)
                is_new = self.rng.random() < 0.2
                suffix = self.rng.choice(NEW_SUFFIXES if is_new else USED_SUFFIXES)
                title = self.rng.choice(TITLE_PREFIXES) + base + suffix
                parts = [
                    self.rng.choice(OPENINGS + (NEW_OPENINGS if is_new else USED_OPENINGS)),
                    self.rng.choice(NEW_STATE if is_new else USED_STATE),
                    *self.rng.sample(details, self.rng.randint(1, min(3, len(details)))),
                    self.rng.choice(DEAL),
                ]
                description = self.description(parts).format(
                    battery=100 if is_new else self.rng.randint(78, 99)
                )
                examples.append(self.example(title, description, root))
        return examples

    def noun_title(self, leaf: str, base: str) -> str:
        noun = self.rng.choice(LEAF_NOUNS[leaf])
        words = base.split()
        tail = " ".join(words[-self.rng.randint(1, 2) :]) if len(words) > 1 else ""
        return f"{noun} {tail}".strip() if self.rng.random() < 0.7 else noun

    def description(self, parts: list[str]) -> str:
        roll = self.rng.random()
        if roll < LATIN_TEXT_RATE:
            return " ".join(self.rng.sample(LATIN_REMARKS, self.rng.randint(1, 2)))
        if roll < LATIN_TEXT_RATE + SHORT_TEXT_RATE:
            return self.rng.choice([*filter(None, parts[1:3]), *SHORT_REMARKS])
        return " ".join(part for part in parts if part)

    def other(self) -> list[Example]:
        examples = []
        for items, details in OTHER_TOPICS.values():
            for _ in range(PER_TOPIC):
                item = self.rng.choice(items)
                if self.rng.random() < NOUN_TITLE_RATE:
                    item = item.split(",")[0].split()[0]
                title = self.rng.choice(TITLE_PREFIXES) + item
                parts = [
                    self.rng.choice(OPENINGS),
                    *self.rng.sample(details, self.rng.randint(1, min(3, len(details)))),
                    self.rng.choice(DEAL),
                ]
                examples.append(self.example(title, self.description(parts), OTHER))
        return examples

    def example(self, title: str, description: str, label: str) -> Example:
        if self.rng.random() < 0.25:
            title = title.lower()
        if self.rng.random() < TYPO_RATE:
            description = self.typo(description)
        if self.rng.random() < 0.1:
            description = description.replace(",", "").replace(".", "")
        return Example(title.strip(), description.strip(), label)

    def typo(self, text: str) -> str:
        words = text.split()
        long_words = [i for i, word in enumerate(words) if len(word) > 4 and word.isalpha()]
        if not long_words:
            return text
        index = self.rng.choice(long_words)
        word = words[index]
        position = self.rng.randrange(1, len(word) - 2)
        if self.rng.random() < 0.5:
            word = word[:position] + word[position + 1] + word[position] + word[position + 2 :]
        else:
            word = word[:position] + word[position + 1 :]
        words[index] = word
        return " ".join(words)
